#!/usr/bin/env node
/**
 * Build latam-builtin-implants-2026.js from latam_master_cases CSV (reconciliation register).
 * Usage: node scripts/build-builtin-implants-2026.mjs path/to/latam_master_cases.csv
 */
import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const XLSX = require('xlsx');

const csvPath = process.argv[2];
if (!csvPath) {
    console.error('Usage: node scripts/build-builtin-implants-2026.mjs <latam_master_cases.csv>');
    process.exit(1);
}

const abs = path.resolve(csvPath);
const wb = XLSX.readFile(abs, { type: 'file', cellDates: true });
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { defval: '', raw: false });

function parseDateParts(dateVal) {
    if (dateVal instanceof Date && !isNaN(dateVal.getTime())) {
        return {
            year: dateVal.getFullYear(),
            display: String(dateVal.getDate()).padStart(2, '0') + '/' + String(dateVal.getMonth() + 1).padStart(2, '0') + '/' + dateVal.getFullYear()
        };
    }
    const raw = String(dateVal ?? '').trim();
    if (/^\d{4}-\d{2}-\d{2}/.test(raw)) {
        const [y, m, d] = raw.split(/[T\s]/)[0].split('-').map(Number);
        return { year: y, display: String(d).padStart(2, '0') + '/' + String(m).padStart(2, '0') + '/' + y };
    }
    const parts = raw.split(/[\/\-]/);
    if (parts.length !== 3) return null;
    let y = parseInt(parts[2], 10);
    if (y < 100) y = y >= 50 ? 1900 + y : 2000 + y;
    let p0 = parseInt(parts[0], 10), p1 = parseInt(parts[1], 10);
    let day, month;
    if (p0 > 12) { day = p0; month = p1; }
    else { month = p0; day = p1; }
    return { year: y, display: String(day).padStart(2, '0') + '/' + String(month).padStart(2, '0') + '/' + y };
}

function parseValve(raw) {
    const u = String(raw).toUpperCase();
    let base = 'Vitae';
    if (u.includes('POWERX') || u.includes('POWER X')) base = 'PowerX';
    else if (u.includes('VENUS P')) base = 'Venus P';
    else if (u.includes('VENUS A')) base = 'Venus A';
    let valve = String(raw).replace(/\s*\|\s*/g, ' ').trim();
    if (base === 'PowerX') valve = valve.replace(/Venus\s+PowerX\s+PowerX/gi, 'Venus PowerX').replace(/PowerX\s+PowerX/gi, 'PowerX');
    return { valve, valveBase: base };
}

function cleanPerson(raw) {
    const s = String(raw ?? '').trim();
    if (!s || /^(none reported|not reported|na|n\/a)$/i.test(s)) return 'N/A';
    return s.split(';').map(p => p.trim()).filter(Boolean).join(', ');
}

function cleanProctor(raw) {
    const s = String(raw ?? '').trim();
    if (!s || /^(none reported|not reported|na|n\/a|false|no)$/i.test(s)) return 'False';
    return s.split(';').map(p => p.trim()).filter(Boolean).join(', ');
}

const baseline = [];
const seen = new Set();

for (const row of rows) {
    const caseId = String(row['Case ID'] || '').trim();
    if (!caseId.includes('2026')) continue;

    const parts = parseDateParts(row.Date);
    if (!parts || parts.year !== 2026) continue;

    const serial = String(row.Serial || '').trim();
    const key = (serial || caseId) + '|' + parts.display;
    if (seen.has(key)) continue;
    seen.add(key);

    const { valve, valveBase } = parseValve(row.Valve || '');
    baseline.push({
        date: parts.display,
        hospital: row.Hospital || 'Unknown Hospital',
        country: row.Country || 'Unknown',
        dist: 'Venus Direct (No Partner)',
        valve,
        valveBase,
        serial: serial || 'N/A',
        implanter: cleanPerson(row.Implanter),
        specialist: cleanPerson(row.Specialist),
        proctor: cleanProctor(row.Proctor),
        _sourceCaseId: caseId
    });
}

baseline.sort((a, b) => a.date.localeCompare(b.date));

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const target = path.join(repoRoot, 'latam-builtin-implants-2026.js');

const js = `// Auto-generated by scripts/build-builtin-implants-2026.mjs — do not edit by hand
// Source: ${path.basename(abs)} | ${baseline.length} master implant cases for 2026 (reconciliation target: 191)
const BUILTIN_IMPLANTS_2026 = ${JSON.stringify(baseline, null, 2)};
if (typeof window !== 'undefined') window.BUILTIN_IMPLANTS_2026 = BUILTIN_IMPLANTS_2026;
`;

fs.writeFileSync(target, js, 'utf8');
console.log(`Wrote ${baseline.length} cases to ${target}`);
if (baseline.length !== 191) {
    console.warn(`Warning: expected 191 cases, got ${baseline.length}`);
}

spawnSync('node', [path.join(repoRoot, 'scripts/inline-builtin-implants.mjs')], { stdio: 'inherit' });
